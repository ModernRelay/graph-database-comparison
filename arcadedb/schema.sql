CREATE VERTEX TYPE Person;
CREATE PROPERTY Person.slug STRING;
CREATE PROPERTY Person.name STRING;
CREATE PROPERTY Person.age INTEGER;
CREATE INDEX ON Person (slug) UNIQUE;
CREATE VERTEX TYPE Company;
CREATE PROPERTY Company.slug STRING;
CREATE PROPERTY Company.name STRING;
CREATE INDEX ON Company (slug) UNIQUE;
CREATE VERTEX TYPE Project;
CREATE PROPERTY Project.slug STRING;
CREATE PROPERTY Project.name STRING;
CREATE INDEX ON Project (slug) UNIQUE;
CREATE EDGE TYPE WorksAt;
CREATE PROPERTY WorksAt.`@out` LINK OF Person;
CREATE PROPERTY WorksAt.`@in` LINK OF Company;
CREATE EDGE TYPE ContributesTo;
CREATE PROPERTY ContributesTo.`@out` LINK OF Person;
CREATE PROPERTY ContributesTo.`@in` LINK OF Project;
