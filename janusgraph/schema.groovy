// Explicit schema through the JanusGraph management API, then one commit.
mgmt = graph.openManagement()
person = mgmt.makeVertexLabel('Person').make()
company = mgmt.makeVertexLabel('Company').make()
project = mgmt.makeVertexLabel('Project').make()
slug = mgmt.makePropertyKey('slug').dataType(String.class).cardinality(Cardinality.SINGLE).make()
name = mgmt.makePropertyKey('name').dataType(String.class).cardinality(Cardinality.SINGLE).make()
age = mgmt.makePropertyKey('age').dataType(Integer.class).cardinality(Cardinality.SINGLE).make()
mgmt.addProperties(person, slug, name, age)
mgmt.addProperties(company, slug, name)
mgmt.addProperties(project, slug, name)
worksAt = mgmt.makeEdgeLabel('WorksAt').multiplicity(Multiplicity.MULTI).make()
contributesTo = mgmt.makeEdgeLabel('ContributesTo').multiplicity(Multiplicity.MULTI).make()
mgmt.addConnection(worksAt, person, company)
mgmt.addConnection(contributesTo, person, project)
mgmt.buildIndex('bySlug', Vertex.class).addKey(slug).unique().buildCompositeIndex()
mgmt.commit()
mgmt = graph.openManagement()
schema = mgmt.printSchema()
mgmt.rollback()
schema
